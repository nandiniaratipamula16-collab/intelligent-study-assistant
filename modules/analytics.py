"""
Analytics and Progress Tracking Module.
Visualizes mastery rates, quiz accuracy, focus streaks, and exports complete study packs.
"""

import datetime
from typing import Dict, Any, List
import pandas as pd

try:
    import plotly.express as px
    import plotly.graph_objects as go
    PLOTLY_AVAILABLE = True
except ImportError:
    PLOTLY_AVAILABLE = False


class StudyAnalytics:
    def __init__(self):
        # We can store metrics in session state or memory
        pass

    @staticmethod
    def create_flashcard_donut_chart(stats: Dict[str, Any]):
        """Create a modern Plotly donut chart showing Leitner card distribution."""
        if not PLOTLY_AVAILABLE or stats.get("total", 0) == 0:
            return None

        labels = ["Learning (Box 1)", "Review (Box 2)", "Mastered (Box 3)"]
        values = [stats.get("learning", 0), stats.get("review", 0), stats.get("mastered", 0)]
        colors = ["#f87171", "#fbbf24", "#34d399"]

        fig = go.Figure(data=[go.Pie(
            labels=labels,
            values=values,
            hole=.55,
            marker=dict(colors=colors),
            textinfo='label+percent',
            hoverinfo='label+value'
        )])
        fig.update_layout(
            title_text="🧠 Flashcard Spaced Repetition Mastery",
            title_x=0.5,
            margin=dict(t=40, b=20, l=20, r=20),
            showlegend=True,
            paper_bgcolor="rgba(0,0,0,0)",
            plot_bgcolor="rgba(0,0,0,0)",
            font=dict(color="#d1d5db" if False else "#374151")
        )
        return fig

    @staticmethod
    def create_quiz_history_chart(quiz_history: List[Dict[str, Any]]):
        """Create a bar/line chart tracking quiz scores over attempts."""
        if not PLOTLY_AVAILABLE or not quiz_history:
            return None

        df = pd.DataFrame(quiz_history)
        fig = px.line(
            df,
            x="attempt",
            y="score_percent",
            markers=True,
            title="📈 Quiz Score Performance Trajectory (%)",
            labels={"attempt": "Quiz Attempt #", "score_percent": "Score (%)"},
            line_shape="spline"
        )
        fig.update_traces(line_color="#4f46e5", line_width=3, marker=dict(size=8, color="#6366f1"))
        fig.update_layout(
            yaxis_range=[0, 105],
            title_x=0.5,
            margin=dict(t=40, b=20, l=20, r=20),
            paper_bgcolor="rgba(0,0,0,0)",
            plot_bgcolor="rgba(0,0,0,0)"
        )
        return fig

    @staticmethod
    def build_study_pack_markdown(
        title: str,
        summary_data: Dict[str, Any],
        flashcards: List[Dict[str, Any]],
        quiz: List[Dict[str, Any]]
    ) -> str:
        """Export comprehensive study pack as clean markdown."""
        date_str = datetime.date.today().strftime("%B %d, %Y")
        lines = [
            f"# 📚 Complete Study Pack: {title}",
            f"*Generated by Intelligent Study Assistant on {date_str}*",
            "\n---\n",
            "## 📌 1. TL;DR",
            summary_data.get("tldr", "N/A"),
            "\n## 📖 2. Executive Summary",
            summary_data.get("executive", "N/A"),
            "\n## 🔑 3. Key Takeaways",
        ]
        
        for bp in summary_data.get("bullet_points", []):
            lines.append(f"- {bp}")

        lines.append("\n## 📘 4. Key Terminology & Definitions")
        for d in summary_data.get("definitions", []):
            lines.append(f"- **{d['term']}**: {d['definition']}")

        lines.append("\n---\n## 🗂️ 5. Flashcards Deck")
        for idx, fc in enumerate(flashcards, 1):
            lines.append(f"**Card #{idx} [{fc.get('category', 'General')}]**")
            lines.append(f"- **Q:** {fc['question']}")
            lines.append(f"- **A:** {fc['answer']}\n")

        lines.append("---\n## 📝 6. Practice Quiz & Answers")
        for idx, q in enumerate(quiz, 1):
            lines.append(f"**Question #{idx}** ({q.get('type', 'question').upper()}): {q['question']}")
            if "options" in q:
                for opt in q["options"]:
                    lines.append(f"  - {opt}")
            lines.append(f"*Correct Answer:* **{q.get('correct_answer', '')}**")
            lines.append(f"*Explanation:* {q.get('explanation', '')}\n")

        return "\n".join(lines)
